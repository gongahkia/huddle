import {mkdtempSync, rmSync} from 'node:fs';
import {join, resolve} from 'node:path';
import {tmpdir} from 'node:os';
import {createApp} from '../apps/server/src/app';
import {bootstrap, passwordHash} from '../apps/server/src/auth';
const port = Number(process.env.HUDDLE_TEST_PORT || 4311);
if (!Number.isInteger(port) || port < 1024 || port > 65535 || port === 4310) throw new Error('Use a dedicated fixture port (not 4310).');
const extraOrigins = (process.env.HUDDLE_TEST_REVIEW_ORIGINS || '').split(',').filter(Boolean).map(value => {
 const url = new URL(value);
 if (url.protocol !== 'http:' || !['localhost','127.0.0.1'].includes(url.hostname) || url.origin !== value) throw new Error('Fixture review origins must be exact loopback HTTP origins.');
 return url.origin;
});
const directory = mkdtempSync(join(tmpdir(),'huddle-browser-'));
const {app,db} = await createApp({dbPath: join(directory,'test.sqlite'),baseUrl: `http://127.0.0.1:${port}`,staticRoot: resolve('dist/public'),rateLimits: false});
bootstrap(db,'admin@huddle.test','Alex Admin','huddle-browser-password');
db.run("INSERT INTO users VALUES(?,?,?,?,'member')",'22222222-2222-4222-8222-222222222222','Morgan Designer','member@huddle.test',passwordHash('huddle-member-password'));
db.run('INSERT INTO projects VALUES(?,?,?,?,?)','11111111-1111-4111-8111-111111111111','Studio review',JSON.stringify(['http://localhost:4321','http://localhost:4322','http://localhost:4323','http://localhost:4324','http://localhost:4325',...extraOrigins]),'["staging","production","development"]',new Date().toISOString());
db.run('INSERT INTO memberships VALUES(?,?)','11111111-1111-4111-8111-111111111111','22222222-2222-4222-8222-222222222222');
console.log(await app.listen({host: '127.0.0.1',port}));
for (const signal of ['SIGINT','SIGTERM'] as const) process.once(signal,() => {void app.close().then(() => {rmSync(directory,{recursive: true,force: true}); process.exit(0);});});
